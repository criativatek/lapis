namespace Tests\Feature\Assessment\Analysis;

use App\Http\Middleware\HandleInertiaRequests;
use App\Models\Enrollment;
use App\Models\OrganizationSubscription;
use App\Models\Plan;
use App\Models\SchoolClass;
use App\Models\SubscriptionStatus;
use App\Models\User;
use App\Services\Assessment\ProposeClassifications;
use App\Support\Entitlements\Entitlements;
use App\Support\Tenancy\CurrentOrganization;
use Database\Seeders\DemoDataSeeder;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Carbon;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\Test;
use Tests\TestCase;

/**
 * The pages the advanced analysis will stand beside, as they are TODAY — for the Base
 * plan and for the Pro plan alike.
 *
 * WHAT THIS HOLDS. The Fatia D builds a Pro layer on top of Estatística, Evolução do
 * Aluno and the Pauta. The promise to every Base organization is that none of them
 * changes: not a figure, not a key, not a byte. And the promise about Pro is just as
 * firm in the other direction — what Pro sees today on those pages is what it sees
 * until a step says otherwise on purpose.
 *
 * HOW. For each page, the props the server hands to the browser (the SHARED ones — the
 * menu, the organization, the modules — excluded: they belong to no page) are read
 * into two things:
 *
 *  - the inventory of KEY PATHS (`students[].domains[].evolution.points`), readable and
 *    diffable, because the danger of a Pro reading is a KEY that appears where it
 *    should not: a key in the props is a key in the browser's memory (§8.2 of CLAUDE.md);
 *  - a HASH of the whole normalised payload — every value — because a path can stay while
 *    its figure moves.
 *
 * The files in `tests/Fixtures/AdvancedAnalysis/` were generated by the code BEFORE the
 * Fatia D touched anything. A step that changes one of them is changing a page somebody
 * already has; it must say so in its PR and regenerate the file on purpose.
 */
class BasePagesCharacterizationTest extends TestCase
{
    use RefreshDatabase;

    private const FIXTURES = __DIR__.'/../../../Fixtures/AdvancedAnalysis/';

    private User $teacher;

    protected function setUp(): void
    {
        parent::setUp();

        $this->teacher = User::factory()->create(['email' => 'ana.martins@lapis.test']);
        $this->seed(DemoDataSeeder::class);

        // Inside the 1.º Semestre of the demo (14/09/2026 to 29/01/2027), frozen so the payload is.
        $this->travelTo(Carbon::parse('2026-12-15 10:00:00'));

        $this->asTenant(function (): void {
            $class = SchoolClass::where('label', '7.º A')->firstOrFail();
            app(ProposeClassifications::class)->forPeriod($class, $class->academicYear->periods()->where('sequence', 1)->firstOrFail());
        });

        $this->decide('Carolina Nunes', '4');
        $this->decide('Ana Marques', '5');
    }

    /**
     * @template TReturn
     *
     * @param  callable(): TReturn  $callback
     * @return TReturn
     */
    private function asTenant(callable $callback): mixed
    {
        return app(CurrentOrganization::class)->runFor($this->teacher->personalOrganization(), $callback);
    }

    private function subscribe(string $plan): void
    {
        OrganizationSubscription::withoutGlobalScope('organization')->updateOrCreate(
            ['organization_id' => $this->teacher->personalOrganization()->id],
            [
                'plan_id' => Plan::where('key', $plan)->firstOrFail()->id,
                'status' => SubscriptionStatus::Active,
                'starts_at' => Carbon::parse('2026-01-01 00:00:00'),
                'ends_at' => null,
            ],
        );
        app(Entitlements::class)->flush();
    }

    private function decide(string $name, string $code): void
    {
        [$classUlid, $periodUlid, $enrollmentUlid, $levelId] = $this->asTenant(function () use ($name, $code): array {
            $class = SchoolClass::where('label', '7.º A')->firstOrFail();

            return [
                $class->ulid,
                $class->academicYear->periods()->where('sequence', 1)->firstOrFail()->ulid,
                $class->enrollments()->with('student.identity')->get()
                    ->first(fn (Enrollment $candidate): bool => $candidate->student->identity->display_name === $name)->ulid,
                $class->profileVersion->scale->levels()->where('code', $code)->firstOrFail()->id,
            ];
        });

        $this->actingAs($this->teacher)->post(
            "/classes/{$classUlid}/classifications/{$periodUlid}/{$enrollmentUlid}/decide",
            ['final_scale_level_id' => $levelId],
        )->assertSessionHasNoErrors()->assertRedirect();
    }

    /**
     * @return array<string, string> page => url
     */
    private function pages(): array
    {
        [$class, $period, $student] = $this->asTenant(function (): array {
            $class = SchoolClass::where('label', '7.º A')->firstOrFail();

            return [
                $class->ulid,
                $class->academicYear->periods()->where('sequence', 1)->firstOrFail()->ulid,
                $class->enrollments()->with('student.identity')->get()
                    ->first(fn (Enrollment $candidate): bool => $candidate->student->identity->display_name === 'Carolina Nunes')->ulid,
            ];
        });

        return [
            'statistics' => "/classes/{$class}/results/estatistica/{$period}",
            'student' => "/classes/{$class}/evolucao/{$student}",
            'class-progress' => "/classes/{$class}/evolucao",
            'pauta' => "/classes/{$class}/pauta-avaliacao/{$period}",
        ];
    }

    /**
     * The page's OWN props, normalised: the shared ones out, every ULID and timestamp a placeholder.
     *
     * @return array<string, mixed>
     */
    private function propsOf(string $url): array
    {
        $props = null;

        $this->actingAs($this->teacher)->get($url)->assertOk()->assertInertia(function ($page) use (&$props): void {
            $props = $page->toArray()['props'];
        });

        $shared = array_keys(app(HandleInertiaRequests::class)->share(app('request')));

        foreach ($shared as $key) {
            unset($props[$key]);
        }

        // `errors` and the flash belong to the request, not to the page.
        unset($props['errors'], $props['flash']);

        return $this->normalise($props);
    }

    private function normalise(mixed $value): mixed
    {
        if (is_array($value)) {
            return array_map(fn (mixed $item): mixed => $this->normalise($item), $value);
        }

        if (is_string($value)) {
            $value = preg_replace('/\b[0-9a-z]{26}\b/', 'ULID', $value) ?? $value;

            return preg_replace('/\d{4}-\d\d-\d\d[T ][\d:.]+(Z|[+-]\d\d:?\d\d)?/', 'DATETIME', $value) ?? $value;
        }

        return $value;
    }

    /**
     * Every distinct path of keys, with list positions collapsed: `students[].domains[].evolution`.
     *
     * @return list<string>
     */
    private function paths(mixed $value, string $prefix = ''): array
    {
        if (! is_array($value)) {
            return [$prefix === '' ? '(valor)' : $prefix];
        }

        if ($value === []) {
            return [$prefix === '' ? '(vazio)' : $prefix.' = []'];
        }

        $paths = [];

        foreach ($value as $key => $child) {
            $segment = array_is_list($value) ? '[]' : ".{$key}";
            $paths = [...$paths, ...$this->paths($child, $prefix.$segment)];
        }

        $paths = array_values(array_unique(array_map(fn (string $path): string => ltrim($path, '.'), $paths)));
        sort($paths);

        return $paths;
    }

    /**
     * @return iterable<string, array{string, string}>
     */
    public static function everyPageForEveryPlan(): iterable
    {
        foreach (['base', 'pro'] as $plan) {
            foreach (['statistics', 'student', 'class-progress', 'pauta'] as $page) {
                yield "{$page} ({$plan})" => [$page, $plan];
            }
        }
    }

    #[Test]
    #[DataProvider('everyPageForEveryPlan')]
    public function the_page_is_what_it_always_was(string $page, string $plan): void
    {
        $this->subscribe($plan);

        $props = $this->propsOf($this->pages()[$page]);
        $paths = implode("\n", $this->paths($props))."\n";
        $hash = hash('sha256', (string) json_encode($props, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES))."\n";

        $this->assertNotEmpty($props, 'the page has props of its own');
        $this->assertFileExists(self::FIXTURES."{$page}-{$plan}.paths.txt");

        $this->assertSame(
            (string) file_get_contents(self::FIXTURES."{$page}-{$plan}.paths.txt"),
            $paths,
            "{$page} ({$plan}): the set of KEYS the server sends changed. If a Pro reading was added on purpose, regenerate the file in the same PR and say so.",
        );
        $this->assertSame(
            (string) file_get_contents(self::FIXTURES."{$page}-{$plan}.sha256"),
            $hash,
            "{$page} ({$plan}): a VALUE the server sends changed.",
        );
    }

    #[Test]
    public function a_base_page_carries_no_key_of_the_advanced_layer_today_or_tomorrow(): void
    {
        $this->subscribe('base');

        foreach ($this->pages() as $page => $url) {
            $paths = implode("\n", $this->paths($this->propsOf($url)));

            // The Pro readings that exist today (the CLASS-level movement counts and matrix, and the
            // student page's `pro` block — each student's own change is Base and stays), and the words
            // the advanced analysis will use.
            foreach (['evolution.progressed', 'evolution.stable', 'evolution.regressed', 'evolution.transitions', 'evolution.average_change', 'pro.', 'timeline', 'persistent', 'analise'] as $forbidden) {
                $this->assertStringNotContainsString($forbidden, strtolower($paths), "{$page} (base): «{$forbidden}» must not be in the props of a Base page");
            }
        }

        // The Pro reading that already exists is absent for Base and present for Pro: the line is real.
        $basePaths = implode("\n", $this->paths($this->propsOf($this->pages()['statistics'])));
        $this->subscribe('pro');
        $proPaths = implode("\n", $this->paths($this->propsOf($this->pages()['statistics'])));

        $this->assertStringNotContainsString('stats.evolution.progressed', $basePaths);
        $this->assertStringContainsString('evolution.progressed', $proPaths);
    }
}
